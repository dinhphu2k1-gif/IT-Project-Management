#!/bin/bash
# Chạy MỘT LẦN khi khởi tạo: tạo user GoldenGate và schema CORE (core banking giả lập)
# trong PDB FREEPDB1. Mật khẩu lấy từ biến môi trường của docker-compose.

CORE_PASSWORD="${CORE_PASSWORD:-core}"
GGADMIN_PASSWORD="${GGADMIN_PASSWORD:-ggadmin}"

sqlplus -s / as sysdba <<SQL
SET ECHO ON FEEDBACK ON
WHENEVER SQLERROR CONTINUE

-- User GoldenGate mức CDB (cho Extract đăng ký ở CDB\$ROOT, nếu bản cài dùng cách này)
CREATE USER c##ggadmin IDENTIFIED BY "${GGADMIN_PASSWORD}" CONTAINER=ALL;
GRANT CREATE SESSION, ALTER SESSION, SET CONTAINER, SELECT ANY DICTIONARY, SELECT ANY TABLE,
      FLASHBACK ANY TABLE, LOGMINING TO c##ggadmin CONTAINER=ALL;
ALTER USER c##ggadmin QUOTA UNLIMITED ON users CONTAINER=ALL;
BEGIN
  EXECUTE IMMEDIATE 'GRANT OGG_CAPTURE TO c##ggadmin CONTAINER=ALL';
EXCEPTION WHEN OTHERS THEN
  DBMS_GOLDENGATE_AUTH.GRANT_ADMIN_PRIVILEGE('C##GGADMIN', container => 'ALL');
END;
/

ALTER SESSION SET CONTAINER = FREEPDB1;

-- User GoldenGate mức PDB (cho Per-PDB Extract, cách khuyến nghị từ 21c)
CREATE USER ggadmin IDENTIFIED BY "${GGADMIN_PASSWORD}" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, ALTER SESSION, SELECT ANY DICTIONARY, SELECT ANY TABLE,
      FLASHBACK ANY TABLE, LOGMINING, CREATE TABLE TO ggadmin;
BEGIN
  EXECUTE IMMEDIATE 'GRANT OGG_CAPTURE TO ggadmin';
EXCEPTION WHEN OTHERS THEN
  DBMS_GOLDENGATE_AUTH.GRANT_ADMIN_PRIVILEGE('GGADMIN', container => 'CURRENT');
END;
/

-- Schema core banking
CREATE USER core IDENTIFIED BY "${CORE_PASSWORD}" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO core;

CREATE TABLE core.branch (
  branch_id    NUMBER(6)     PRIMARY KEY,
  branch_code  VARCHAR2(10)  NOT NULL UNIQUE,
  branch_name  VARCHAR2(100) NOT NULL,
  city         VARCHAR2(50)  NOT NULL
);

CREATE TABLE core.customer (
  customer_id  NUMBER(10)    PRIMARY KEY,
  full_name    VARCHAR2(100) NOT NULL,
  segment      VARCHAR2(20)  NOT NULL,
  branch_id    NUMBER(6)     NOT NULL REFERENCES core.branch,
  created_at   TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
);

CREATE TABLE core.account (
  account_id   NUMBER(12)    PRIMARY KEY,
  account_no   VARCHAR2(20)  NOT NULL UNIQUE,
  customer_id  NUMBER(10)    NOT NULL REFERENCES core.customer,
  branch_id    NUMBER(6)     NOT NULL REFERENCES core.branch,
  currency     CHAR(3)       DEFAULT 'VND' NOT NULL,
  balance      NUMBER(18,2)  DEFAULT 0 NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  updated_at   TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
);

-- created_at lưu theo giờ UTC, dùng để đo độ trễ end-to-end ở ClickHouse
CREATE TABLE core.txn (
  txn_id       NUMBER(15)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id   NUMBER(12)    NOT NULL REFERENCES core.account,
  branch_id    NUMBER(6)     NOT NULL REFERENCES core.branch,
  channel      VARCHAR2(10)  NOT NULL CHECK (channel IN ('ATM','POS','MOBILE','INTERNET','COUNTER')),
  txn_type     VARCHAR2(20)  NOT NULL CHECK (txn_type IN ('DEPOSIT','WITHDRAW','TRANSFER_OUT','TRANSFER_IN','PAYMENT')),
  amount       NUMBER(18,2)  NOT NULL CHECK (amount > 0),
  currency     CHAR(3)       DEFAULT 'VND' NOT NULL,
  created_at   TIMESTAMP(6)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  description  VARCHAR2(200)
);
CREATE INDEX core.txn_account_ix ON core.txn (account_id, created_at);

SELECT owner, table_name FROM dba_tables WHERE owner = 'CORE' ORDER BY table_name;
SQL
